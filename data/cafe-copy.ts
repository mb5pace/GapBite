/** Why a cafe turns an order down. `buyerText` finishes the sentence "... because ...". */
export const REJECT_REASONS = [
  { id: "ran-out", label: "An item ran out", buyerText: "an item ran out" },
  { id: "kitchen-closed", label: "Kitchen is closed", buyerText: "the kitchen is closed right now" },
  { id: "too-busy", label: "Too many orders", buyerText: "there are too many orders right now" },
  { id: "other", label: "Something else", buyerText: "of a problem at the counter" },
] as const;

export type RejectReasonId = (typeof REJECT_REASONS)[number]["id"];

export const REJECT_REASON_IDS = REJECT_REASONS.map((reason) => reason.id) as [RejectReasonId, ...RejectReasonId[]];

export function rejectReason(id: string): (typeof REJECT_REASONS)[number] | undefined {
  return REJECT_REASONS.find((reason) => reason.id === id);
}

